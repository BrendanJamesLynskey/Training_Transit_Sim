def rows_for(variants=VARIANTS, modules=("low", "high", "free")):
    """(row name, variant, module key or None): each in-transit variant once per module setting."""
    out = []
    for v in variants:
        if v in TRANSIT:
            out += [(f"{VARIANTS[v]['name']} [{m}]", v, m) for m in modules]
        else:
            out.append((VARIANTS[v]["name"], v, None))
    return out


def cfg(v, topo, m=None, **kw):
    return Config(v, topo, module=MODULES[m or "high"], **kw)


def fmt(x, nd=2):
    if x is None or (isinstance(x, float) and math.isinf(x)):
        return "not reached"
    return f"{x:,.{nd}f}"


def gbs(x):
    return "none in range" if x is None else f"{x / GB:,.3g} GB/s ({x * 8 / 1e9:,.3g} Gb/s)"


JSON_SIG = 6


def rounded(obj):
    if isinstance(obj, dict):
        return {str(k): rounded(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [rounded(v) for v in obj]
    if isinstance(obj, float):
        if not math.isfinite(obj) or obj.is_integer():
            return obj if math.isfinite(obj) else None
        return float(f"{obj:.{JSON_SIG}g}")
    return obj


def main() -> None:
    exp = inputs.load()
    src = json.loads((inputs.DATA / "SOURCE.json").read_text())
    S = exp.setup
    res: dict = {"experiment": {"commit": src["commit"], "sha256": src["sha256"], "params": S.params,
                                "workers": S.workers, "tokens_per_worker": S.tokens_per_worker}}
    L: list[str] = []
    w = L.append
    w("# Recorded results\n")
    w(f"Generated by `examples/results.py` (training-transit-sim {__version__}; {platform.machine()}, Python "
      f"{sys.version.split()[0]}, SimPy {simpy.__version__}). Every number in the README comes from this file. "
      f"Inputs: DeMo_Fixed_Band_Experiment at commit `{src['commit'][:7]}` "
      "(`results/tinystories-gpu/results.json` and `results.md`, vendored in `data/experiment/` with their SHA-256). "
      "Devices and links: Disaggregated_Inference_Sim at `69ffd2b` (`disagg_sim.hardware`).\n")
    w(f"Setup taken from the experiment: {S.params:,} parameters, {S.workers} workers, {S.seqs_per_worker} sequences "
      f"of {S.context} tokens per worker per step ({S.tokens_per_worker:,} tokens), an H100 per worker at an MFU of "
      "0.40 (illustrative). Target loss for the headline tables: "
      f"**{TARGET}** (the 2-D fixed band's final loss), the one ladder loss that the dense, top-k, exact-band and "
      "optics variants all reach.\n")
    w("**Measured, assumed and illustrative.** Steps to a loss are measured (one model size, 8 workers, 3,000 steps; "
      "A to C three seeds, every E run one seed). The two hypothetical variants (C' and E') were not run: they reuse "
      "C's and E's steps because summing the band gives the same update as gathering it. That the repaired optics "
      "band needs fewer steps than the exact band is a **hypothesis** from single seeds, so the in-transit rows are "
      "also given with the exact band's steps (section 2). Every module coefficient except the 9.7 W static power "
      "(the paper), the 2.76 pJ/bit (the developer's website, 45 nm, excluding the laser), the 25 GB/s port and the "
      "4 x 14 Gb/s optics (the series' arithmetic from the paper) is illustrative, as are the WAN presets and the "
      "MFU.\n")

    # ── 1. inputs ──
    w("## 1. Inputs from the experiment, and the wire bytes the model sends\n")
    w("Payload = bytes a worker originates per step (results.json); the model scales it with the parameter count by "
      "the measured bytes per parameter. *Model wire* = what a worker sends in the model's ring collective with 8 "
      "workers in one DC; it must equal the experiment's wire column.\n")
    w("| Variant | Collective | Payload / step (bytes) | Bytes per parameter | Model wire / step (bytes) | "
      "Experiment wire / step (bytes) |")
    w("|---|---|---|---|---|---|")
    one = TOPOLOGIES["1 DC x 8"]
    res["inputs"] = []
    for v in ("adamw", "topk", "band", "band-allreduce", "band-pluggable", "band-switch"):
        p = plan(cfg(v, one))
        lab = VARIANTS[v]["label"] or inputs.label_optics()
        model_wire = p.schedule.sent_by(0)
        coll = {"adamw": "ring all-reduce", "band-allreduce": "ring all-reduce",
                "band-switch": "to the switch, summed"}.get(v, "ring all-gather")
        exp_wire = exp.row(lab)["wire_per_step"] if v not in HYPOTHETICAL else None
        w(f"| {VARIANTS[v]['name']} | {coll} | {p.payload:,.0f} | {exp.bytes_per_param(lab):.4f} | {model_wire:,.0f} | "
          f"{'n/a (not run)' if exp_wire is None else f'{exp_wire:,.0f}'} |")
        res["inputs"].append(dict(variant=v, payload=p.payload, bytes_per_param=exp.bytes_per_param(lab),
                                  model_wire=model_wire, experiment_wire=exp_wire))
    w("\n* E' sends its dense delta (2 bytes per parameter) up to the switch, where the band is computed; what crosses "
      "the WAN is the band sum. C' is the band summed by an ordinary ring all-reduce at the workers, no module.\n")
    w("Steps to reach each loss (results.md section 1, *Steps to reach a loss*; – = not every seed reached it):\n")
    w("| Steps from | " + " | ".join(f"{t:.3f} ({k})" for t, k in exp.targets) + " |")
    w("|---|" + "---|" * len(exp.targets))
    res["ladder"] = {}
    for lab in (inputs.LABEL_ADAMW, inputs.LABEL_TOPK, inputs.LABEL_BAND, *(inputs.label_optics(e) for e in inputs.ENOBS)):
        cells = [exp.steps_to(lab, t) for t, _ in exp.targets]
        res["ladder"][lab] = cells
        w(f"| {lab} | " + " | ".join("–" if c is None else f"{c:,.0f}" for c in cells) + " |")

    # ── 2. time to target ──
    w(f"\n## 2. Time to {TARGET} by topology\n")
    w("Module settings: " + "; ".join(f"**[{k}]** {t}" for k, t in MODULE_TEXT.items()) + ". Intra-DC links: "
      "InfiniBand NDR 400G (50 GB/s) per worker. The 400G and 800G WAN presets and the 8 Gb/s WAN share (the 100 GbE "
      "preset at 1 GB/s) are illustrative.\n")
    names = list(TOPOLOGIES)
    res["time_to_target"] = {}
    tables = {"step": [], "time": [], "hot": []}
    for rn, v, m in rows_for():
        cells = {}
        for tn in names:
            o = evaluate(cfg(v, TOPOLOGIES[tn], m), TARGET)
            cells[tn] = o
            res["time_to_target"].setdefault(rn, {})[tn] = dict(steps=o.steps, step_ms=o.step_time * 1e3,
                                                                seconds=None if math.isinf(o.time) else o.time,
                                                                hot_spot=o.result.hot_spot)
        tables["step"].append(f"| {rn} | " + " | ".join(fmt(cells[t].step_time * 1e3, 3) for t in names) + " |")
        tables["time"].append(f"| {rn} | {fmt(cells[names[0]].steps, 0)} | "
                              + " | ".join(fmt(cells[t].time) for t in names) + " |")
        tables["hot"].append(f"| {rn} | " + " | ".join(cells[t].result.hot_spot for t in names) + " |")
    w("Step time (ms, compute + one sync):\n")
    w("| Variant | " + " | ".join(names) + " |")
    w("|---|" + "---|" * len(names))
    L.extend(tables["step"])
    w(f"\nTime to {TARGET} (seconds = steps x step time):\n")
    w("| Variant | Steps | " + " | ".join(names) + " |")
    w("|---|---|" + "---|" * len(names))
    L.extend(tables["time"])
    w("\nHot spot (the category that holds the largest share of the step):\n")
    w("| Variant | " + " | ".join(names) + " |")
    w("|---|" + "---|" * len(names))
    L.extend(tables["hot"])
    w(f"\nWithout the hypothesis: the in-transit variants with the exact band's steps (C, 3 seeds) instead of E's "
      f"(one seed), {BASE}:\n")
    w("| Variant | Steps (E, ENOB 8) | Time (s) | Steps (C, exact band) | Time (s) |")
    w("|---|---|---|---|---|")
    res["exact_steps"] = {}
    for rn, v, m in rows_for(TRANSIT):
        a = evaluate(cfg(v, TOPOLOGIES[BASE], m), TARGET)
        b = evaluate(cfg(v, TOPOLOGIES[BASE], m, exact_steps=True), TARGET)
        res["exact_steps"][rn] = dict(e_steps=a.steps, e_time=a.time, c_steps=b.steps, c_time=b.time)
        w(f"| {rn} | {fmt(a.steps, 0)} | {fmt(a.time)} | {fmt(b.steps, 0)} | {fmt(b.time)} |")

    # ── 3. every ladder loss ──
    w(f"\n## 3. Time to every ladder loss ({BASE}, module [high])\n")
    w("| Variant | " + " | ".join(f"to {t:.3f}" for t, _ in exp.targets) + " |")
    w("|---|" + "---|" * len(exp.targets))
    res["ladder_times"] = {}
    for rn, v, m in rows_for(modules=("high",)):
        ts = [evaluate(cfg(v, TOPOLOGIES[BASE], m), t).time for t, _ in exp.targets]
        res["ladder_times"][rn] = [None if math.isinf(x) else x for x in ts]
        w(f"| {rn} | " + " | ".join(fmt(x) for x in ts) + " |")

    # ── 4. link utilisation ──
    w(f"\n## 4. Link and module utilisation ({BASE})\n")
    w("Busy time of the busiest resource of each kind over the simulated step (compute + sync). *Worker port up* = a "
      "worker's link to its DC fabric; *switch to worker* = the return direction the switch variant uses; "
      "*inter-DC* = a DC's WAN link.\n")
    w("| Variant | Worker port up | Switch to worker | Inter-DC | Busiest module |")
    w("|---|---|---|---|---|")
    res["utilisation"] = {}
    for rn, v, m in rows_for():
        r = evaluate(cfg(v, TOPOLOGIES[BASE], m), TARGET).result
        u = {k: r.utilisation(k) for k in ("up", "down", "wan", "mod")}
        res["utilisation"][rn] = u
        w(f"| {rn} | " + " | ".join(f"{100 * u[k]:.1f}%" for k in ("up", "down", "wan", "mod")) + " |")

    # ── 5. energy ──
    w(f"\n## 5. Energy ({BASE})\n")
    w("Per step, all 8 workers: compute = each H100's static power (100 W, disagg-sim's illustrative figure) for the "
      "whole step + 1 pJ per FLOP; link = pJ/bit of each preset over every byte; module = (9.7 W static + 2 W laser, "
      "illustrative) per module for the whole step + 2.76 pJ/bit over the bytes it processes. Energy to target = "
      "steps x energy per step.\n")
    w("| Variant | Compute (J/step) | Link (J/step) | Module (J/step) | Module share | Energy to target (kJ) |")
    w("|---|---|---|---|---|---|")
    res["energy"] = {}
    for rn, v, m in rows_for():
        o = evaluate(cfg(v, TOPOLOGIES[BASE], m), TARGET)
        e = o.energy_per_step
        tot = sum(e.values())
        res["energy"][rn] = dict(**e, to_target_j=None if math.isinf(o.energy) else o.energy)
        w(f"| {rn} | {e['compute']:.3f} | {e['link']:.4f} | {e['module']:.3f} | {100 * e['module'] / tot:.1f}% | "
          f"{fmt(o.energy / 1e3, 2)} |")

    # ── 6. hot spots ──
    w(f"\n## 6. Hot-spot attribution ({BASE})\n")
    w("Share of the step each category holds: each round of the sync is charged to its slowest op. The module's "
      "time is split by its binding stage (port, optics, compute budget or FPGA).\n")
    w("| Variant | " + " | ".join(CATEGORIES) + " |")
    w("|---|" + "---|" * len(CATEGORIES))
    res["hot_spots"] = {}
    for rn, v, m in rows_for():
        h = evaluate(cfg(v, TOPOLOGIES[BASE], m), TARGET).result.hot_spots()
        res["hot_spots"][rn] = h
        w(f"| {rn} | " + " | ".join(f"{100 * h[c]:.1f}%" for c in CATEGORIES) + " |")
    dense0 = plan(cfg("band-pluggable", TOPOLOGIES[BASE])).dense
    st = MODULES["high"].stage_times(dense0, band_kernel())
    st_low = MODULES["low"].stage_times(dense0, band_kernel())
    res["module_stages_dense"] = st
    w("\nOne worker's dense delta through the module (ms per stage; the stages are pipelined, the slowest sets the "
      "time): " + ", ".join(f"{k} {1e3 * x:.3f}" for k, x in st.items())
      + f" at [high]; the compute stage is {1e3 * st_low['module compute']:.3f} ms at [low] "
      "and zero when the transform is not charged.\n")

    # ── 7. break-even ──
    w("## 7. Break-even points (bisection)\n")
    w(f"Each is the value where X's time to {TARGET} equals Y's, found by bisection to a relative tolerance of 1e-4; "
      "*none in range* = one variant is faster across the whole range (the sign of X - Y at both ends is shown).\n")
    w("### 7a. Over the inter-DC bandwidth (2 DC x 4, 0.1 to 1,000 GB/s)\n")
    w("| X | Y | Module | Steps | Break-even | X - Y at 0.1 GB/s (s) | X - Y at 1,000 GB/s (s) | Faster below |")
    w("|---|---|---|---|---|---|---|---|")
    pairs = [("band-switch", "adamw"), ("band-switch", "topk"), ("band-switch", "band-allreduce"),
             ("band-pluggable", "adamw"), ("band-pluggable", "topk"), ("band-pluggable", "band"), ("band-allreduce", "adamw"),
             ("band-allreduce", "topk"), ("band", "adamw"), ("topk", "adamw")]
    res["breakeven_bw"] = []
    for x, y in pairs:
        for m in (("free", "high") if x in TRANSIT else ("high",)):
            for exact in ((False, True) if x in TRANSIT else (False,)):
                be = bisect(gap(cfg(x, TOPOLOGIES[BASE], m, exact_steps=exact), cfg(y, TOPOLOGIES[BASE], m), TARGET,
                                knob_inter_bw), 0.1 * GB, 1000 * GB)
                below = (VARIANTS[x]["name"][:2].strip() if be.f_lo < 0 else VARIANTS[y]["name"][:2].strip())
                steps = "C (exact)" if exact else ("E" if x in TRANSIT else "measured")
                res["breakeven_bw"].append(dict(x=x, y=y, module=m, exact_steps=exact, bw=be.x, f_lo=be.f_lo,
                                                f_hi=be.f_hi, iterations=be.iterations))
                w(f"| {VARIANTS[x]['name']} | {VARIANTS[y]['name']} | {m if x in TRANSIT else '–'} | {steps} | "
                  f"{gbs(be.x)} | {be.f_lo:+.2f} | {be.f_hi:+.2f} | {below} |")

    w("\n### 7b. Over the module's compute budget (transform charged; 1 to 100,000 GFLOP/s)\n")
    w("| X | Y | Topology | Break-even | X - Y at 1 GFLOP/s (s) | X - Y at 100,000 GFLOP/s (s) |")
    w("|---|---|---|---|---|---|")
    res["breakeven_gflops"] = []
    for x, y, tn in (("band-pluggable", "band", BASE), ("band-switch", "adamw", BASE),
                     ("band-pluggable", "band", SLOW), ("band-switch", "adamw", SLOW), ("band-switch", "topk", SLOW),
                     ("band-switch", "band-allreduce", SLOW), ("band-switch", "adamw", "8 DC x 1, 25 GbE")):
        be = bisect(gap(cfg(x, TOPOLOGIES[tn], "high"), cfg(y, TOPOLOGIES[tn], "high"), TARGET, knob_gflops), 1e9, 1e14)
        res["breakeven_gflops"].append(dict(x=x, y=y, topology=tn, gflops=be.x, f_lo=be.f_lo, f_hi=be.f_hi))
        w(f"| {VARIANTS[x]['name']} | {VARIANTS[y]['name']} | {tn} | "
          f"{'none in range' if be.x is None else f'{be.x / 1e9:,.1f} GFLOP/s'} | {be.f_lo:+.2f} | {be.f_hi:+.2f} |")
    dense = plan(cfg("band-pluggable", TOPOLOGIES[BASE])).dense

    def binding_gap(g):
        s = replace(MODULES["high"], gflops=g).stage_times(dense, band_kernel())
        return s["module compute"] - max(v for k, v in s.items() if k != "module compute")
    be = bisect(binding_gap, 1e9, 1e14)
    res["gflops_unbound"] = be.x
    w(f"\n* The module's compute budget stops being its bottleneck (for the 1-D 256-point band, transform charged, "
      f"8 planes) at **{be.x / 1e9:,.1f} GFLOP/s**; above that the optics binds. The series' bracket is 10 to 99 "
      "GFLOP/s.\n")

    w("### 7c. Over ENOB (through the measured E runs)\n")
    w("ENOB enters only through convergence: the steps of the E run at that ENOB (8 planes, full scale re-set every "
      "100 steps, feedback of the band sent; one seed each). Between the measured 6, 8, 10 and 12 the steps of the run "
      "below are used (a step function), so a break-even lands on a measured ENOB.\n")
    w("| ENOB | " + " | ".join(f"steps to {t:.3f}" for t, _ in exp.targets) + " |")
    w("|---|" + "---|" * len(exp.targets))
    never = []
    res["enob_steps"] = {}
    for e in inputs.ENOBS:
        cells = [exp.steps_to(inputs.label_optics(e), t) for t, _ in exp.targets]
        res["enob_steps"][e] = cells
        if all(c is None for c in cells):
            never.append(e)
        w(f"| {e} | " + " | ".join("never" if c is None else f"{c:,.0f}" for c in cells) + " |")
    unreached = [t for t, _ in exp.targets if all(exp.steps_to(inputs.label_optics(e), t) is None for e in inputs.ENOBS)]
    res["enob_never"] = never
    res["targets_no_enob_reaches"] = unreached
    w(f"\n* ENOB {', '.join(map(str, never))} never reaches any ladder loss; no ENOB reaches "
      f"{' or '.join(f'{t:.3f}' for t in unreached)} (top-k's and AdamW's final losses).\n")
    w("| X | Y | Topology | Module | Break-even ENOB | X - Y at ENOB 6 (s) | X - Y at ENOB 12 (s) |")
    w("|---|---|---|---|---|---|---|")
    res["breakeven_enob"] = []
    for x, y, tn, m in (("band-pluggable", "band", BASE, "free"), ("band-pluggable", "band", SLOW, "free"),
                        ("band-switch", "adamw", SLOW, "free"), ("band-switch", "topk", SLOW, "free"),
                        ("band-switch", "band-allreduce", SLOW, "free"), ("band-switch", "adamw", SLOW, "high")):
        be = bisect(gap(cfg(x, TOPOLOGIES[tn], m), cfg(y, TOPOLOGIES[tn], m), TARGET, knob_enob), 6.0, 12.0,
                    log=False, rel_tol=1e-6)
        grid = None if be.x is None else min(e for e in inputs.ENOBS if e >= be.x - 1e-3)
        res["breakeven_enob"].append(dict(x=x, y=y, topology=tn, module=m, enob=be.x, measured_enob=grid,
                                          f_lo=be.f_lo, f_hi=be.f_hi))
        w(f"| {VARIANTS[x]['name']} | {VARIANTS[y]['name']} | {tn} | {m} | "
          f"{'none in range' if be.x is None else f'{grid} (bisection: {be.x:.4f})'} | {fmt(be.f_lo)} | {fmt(be.f_hi)} |")
    assert measured_enob(7.99) == 6

    # ── 8. planes ──
    w(f"\n## 8. Bit planes: throughput against convergence ({BASE}, ENOB 8)\n")
    w("Each plane is one optical pass, so the optics' time grows with the planes; the steps come from the E runs at "
      "4, 8 and 12 planes (one seed each).\n")
    w("| Planes | Module | Steps to target | Optics stage, one dense delta (ms) | Step (ms) E | Time to target (s) E | "
      "Step (ms) E' | Time to target (s) E' |")
    w("|---|---|---|---|---|---|---|---|")
    res["planes"] = []
    for pl in inputs.PLANES:
        for m in ("free", "high"):
            mod = replace(MODULES[m], planes=pl)
            a = evaluate(Config("band-pluggable", TOPOLOGIES[BASE], module=mod), TARGET)
            b = evaluate(Config("band-switch", TOPOLOGIES[BASE], module=mod), TARGET)
            opt = mod.stage_times(a.result.plan.dense, band_kernel(planes=pl))["module optics"]
            res["planes"].append(dict(planes=pl, module=m, steps=a.steps, optics_ms=opt * 1e3, e_step_ms=a.step_time * 1e3,
                                      e_time=a.time, e2_step_ms=b.step_time * 1e3, e2_time=b.time))
            w(f"| {pl} | {m} | {fmt(a.steps, 0)} | {opt * 1e3:.3f} | {a.step_time * 1e3:.3f} | {fmt(a.time)} | "
              f"{b.step_time * 1e3:.3f} | {fmt(b.time)} |")

    # ── 9. background load ──
    w(f"\n## 9. Queueing on a shared WAN ({BASE}; discrete-event only)\n")
    w("Other jobs' traffic on each inter-DC link: a Poisson stream of 1 MB transfers at the given share of its "
      "capacity, first come first served with the sync. Mean over 200 syncs (seed 0). At zero load the simulated step "
      "equals the closed form; the closed form cannot see the queueing.\n")
    w("| Variant | Closed form (ms) | Load 0 | Load 0.3 | Load 0.6 | Load 0.9 | WAN busy at 0.9, incl. background |")
    w("|---|---|---|---|---|---|---|")
    res["background"] = {}
    queue_rows = ("adamw", "topk", "band", "band-switch", "band-allreduce")
    for rn, v, m in [r for r in rows_for(modules=("free",)) if r[1] in queue_rows]:
        p = plan(cfg(v, TOPOLOGIES[BASE], m))
        cells, last = [], None
        for load in (0.0, 0.3, 0.6, 0.9):
            r = simulate(p, syncs=200, background=load, seed=0)
            cells.append(r.step_time)
            last = r
        res["background"][rn] = dict(analytic=analytic.step_time(p), loads=[0.0, 0.3, 0.6, 0.9], step=cells,
                                     wan_busy_09=last.utilisation("wan", background=True))
        w(f"| {rn} | {analytic.step_time(p) * 1e3:.3f} | " + " | ".join(f"{c * 1e3:.3f}" for c in cells)
          + f" | {100 * last.utilisation('wan', background=True):.1f}% |")

    # ── 10. extrapolations ──
    w("\n## 10. Extrapolations (labelled: outside the experiment)\n")
    w(f"**Model size.** Bytes scale with the parameter count by each variant's measured bytes per parameter; the steps "
      f"to {TARGET} are assumed unchanged, which the experiment did not test (it ran 15.8M parameters only). "
      f"{BASE}, module [high] and [free], 2,048 tokens per worker per step.\n")
    sizes = {"15.8M (measured)": None, "1B": 1e9, "Llama-3-8B shape": float(LLAMA3_8B.params)}
    w("| Variant | " + " | ".join(f"{k}: time (s)" for k in sizes) + " | hot spot at the largest |")
    w("|---|" + "---|" * len(sizes) + "---|")
    res["extrapolate_size"] = {}
    for rn, v, m in rows_for(modules=("high", "free")):
        outs = [evaluate(cfg(v, TOPOLOGIES[BASE], m, params=P), TARGET) for P in sizes.values()]
        res["extrapolate_size"][rn] = [o.time for o in outs]
        w(f"| {rn} | " + " | ".join(fmt(o.time) for o in outs) + f" | {outs[-1].result.hot_spot} |")
    w(f"\n**DiLoCo-style sync every H steps.** The experiment synced every step; syncing every H steps with the "
      f"same steps to {TARGET} is an assumption, not a measurement (DiLoCo changes the optimiser too). {BASE}.\n")
    w("| Variant | H = 1: time (s) | H = 10 | H = 100 |")
    w("|---|---|---|---|")
    res["extrapolate_h"] = {}
    for rn, v, m in [r for r in rows_for(modules=("free",)) if r[1] in ("adamw", "topk", "band-switch", "band-allreduce")]:
        ts = [evaluate(cfg(v, TOPOLOGIES[BASE], m, sync_every=H), TARGET).time for H in (1, 10, 100)]
        res["extrapolate_h"][rn] = ts
        w(f"| {rn} | " + " | ".join(fmt(t) for t in ts) + " |")

    # ── 11. what this says ──
    tt = res["time_to_target"]
    nm = {v: VARIANTS[v]["name"] for v in VARIANTS}
    sw_free = f"{nm['band-switch']} [free]"
    pl_low = f"{nm['band-pluggable']} [low]"
    pl_free = f"{nm['band-pluggable']} [free]"
    bw = {(d["x"], d["y"], d["module"], d["exact_steps"]): d["bw"] for d in res["breakeven_bw"]}
    w("\n## 11. What this says\n")
    hs = res["hot_spots"]
    sA, sB, sC = (tt[nm[v]][BASE]["steps"] for v in ("adamw", "topk", "band"))
    steps_ab = f"{fmt(sB, 0)} steps each" if sA == sB else f"{fmt(sB, 0)} and {fmt(sA, 0)} steps"
    w(f"* **At the experiment's scale AdamW's step is mostly communication, and the band needs many more steps.** On "
      f"{BASE}, compute is {100 * hs[nm['adamw']]['compute']:.1f}% of AdamW's step. Top-k reaches {TARGET} in "
      f"{fmt(tt[nm['topk']][BASE]['seconds'])} s and AdamW in {fmt(tt[nm['adamw']][BASE]['seconds'])} s "
      f"({steps_ab}); the fixed band on the GPU needs {fmt(tt[nm['band']][BASE]['seconds'])} s "
      f"({fmt(sC, 0)} steps) and the band in transit (E, ENOB 8) {fmt(tt[pl_free][BASE]['steps'], 0)} steps.")
    w(f"* **With the transform charged against the budget, the module is the bottleneck.** At 10 GFLOP/s the band in "
      f"a pluggable takes {fmt(tt[pl_low][BASE]['step_ms'], 3)} ms a step against "
      f"{fmt(tt[nm['band']][BASE]['step_ms'], 3)} ms for the band on the GPU, and module compute holds "
      f"{100 * hs[pl_low]['module compute']:.1f}% of it. The budget would need {res['gflops_unbound'] / 1e9:,.1f} GFLOP/s "
      "before the optics, not the budget, set the module's rate, which is above the series' bracket of 10 to 99 GFLOP/s.")
    w(f"* **A pluggable also caps its worker's port**: module port holds "
      f"{100 * hs[pl_free]['module port']:.1f}% of the [free] pluggable step, "
      "because a 25 GB/s QSFP56 module sits on a 50 GB/s port.")
    ratio = res['inputs'][2]['model_wire'] / res['inputs'][0]['model_wire']
    w(f"* **The pluggable all-gather never breaks even with AdamW or top-k** over 0.1 to 1,000 GB/s of WAN (section 7a): "
      f"an all-gather of the band still sends {res['inputs'][2]['model_wire']:,.0f} bytes per worker, {ratio:.2f} of "
      f"AdamW's {res['inputs'][0]['model_wire']:,.0f}, while it needs {fmt(tt[pl_low][BASE]['steps'], 0)} steps to "
      f"AdamW's {fmt(sA, 0)}.")
    w(f"* **Summing in the network is where a fixed band could gain.** E' (band computed and summed at the switch, "
      f"each worker's own band looped back) beats AdamW below {gbs(bw[('band-switch', 'adamw', 'free', False)])} of WAN "
      f"and top-k below {gbs(bw[('band-switch', 'topk', 'free', False)])}, with E's steps and the transform not "
      f"charged. With the exact band's steps (no hypothesis) the AdamW crossing falls to "
      f"{gbs(bw[('band-switch', 'adamw', 'free', True)])}.")
    c2 = bw[("band-switch", "band-allreduce", "free", True)]
    c2_text = "never beats C' in range" if c2 is None else "beats C' below " + gbs(c2)
    w(f"* **The same summation without a module does better.** C' (the band computed on the GPU and ring "
      f"all-reduced, no module) beats AdamW below {gbs(bw[('band-allreduce', 'adamw', 'high', False)])}; with both on "
      f"the exact band's steps, E' {c2_text}. "
      "Only E's single-seed step advantage (the hypothesis) lets E' beat C' at all.")
    ens = sorted({d["measured_enob"] for d in res["breakeven_enob"] if d["measured_enob"] is not None})
    w(f"* **ENOB.** ENOB {', '.join(map(str, never))} never reaches a ladder loss. Where an in-transit variant wins "
      f"at all, the break-even ENOB is {', '.join(map(str, ens)) or 'not found'} (section 7c): the lowest measured "
      "ENOB that trains.")
